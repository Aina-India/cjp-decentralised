#!/usr/bin/env node
// Deterministic generator for testdata/latest.vectors.json — the cross-language
// signature-verification contract read by BOTH the Go tests (mirror + publisher)
// and the JS test (packages/site/test/verify-logic.test.mjs).
//
// SECURITY: the Ed25519 keys here are TEST FIXTURES, not secrets. Their seeds
// are derived deterministically from fixed strings and live only in memory —
// no private key is ever written to disk or committed. Only public keys and
// signatures land in the output JSON. Never point this at a real signing key.
//
// Signing scheme (must match packages/{mirror,publisher}/signing.go and
// packages/site/js/verify.js):
//   Ed25519.Sign( SHA-256( "{cid}\n{version}\n{timestamp}" ) )
// i.e. the signed payload is the 32-byte SHA-256 digest, not the raw string.

import { createHash, createPrivateKey, createPublicKey, sign as edSign } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// ── Ed25519 helpers built on raw 32-byte seeds (Node KeyObjects need DER) ──
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex'); // Ed25519 PKCS#8 seed wrapper
const SPKI_PREFIX  = Buffer.from('302a300506032b6570032100', 'hex');         // Ed25519 SPKI pubkey wrapper

// Deterministic, reproducible test key from a label — NOT a real key.
function testKeyFromLabel(label) {
  const seed = createHash('sha256').update(label).digest(); // 32 bytes
  const priv = createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, seed]), format: 'der', type: 'pkcs8' });
  const spki = createPublicKey(priv).export({ format: 'der', type: 'spki' });
  const pub  = spki.subarray(spki.length - 32); // raw 32-byte public key
  return { priv, pubHex: Buffer.from(pub).toString('hex') };
}

function signingDigest(cid, version, timestamp) {
  return createHash('sha256').update(`${cid}\n${version}\n${timestamp}`).digest();
}

function signHex(priv, cid, version, timestamp) {
  return edSign(null, signingDigest(cid, version, timestamp), priv).toString('hex');
}

// Flip the final hex nibble so the signature no longer verifies.
function tamper(sigHex) {
  const last = parseInt(sigHex[sigHex.length - 1], 16);
  return sigHex.slice(0, -1) + (last ^ 0x1).toString(16);
}

// ── Two reproducible test signers ──
const k1 = testKeyFromLabel('cjp-test-vector-key-v1'); // "trusted" in most vectors
const k2 = testKeyFromLabel('cjp-test-vector-key-v2'); // untrusted / second key

// Fixed base pointer (values are arbitrary but stable for determinism).
const cid = 'bafybeibcjptestvector00000000000000000000000000000000000000000';
const version = 42;
const timestamp = 1700000000;

const sig1 = signHex(k1.priv, cid, version, timestamp);
const sig2 = signHex(k2.priv, cid, version, timestamp);

const vectors = [
  {
    name: 'valid_multisig',
    description: 'One valid signature from the sole trusted signer, threshold 1 → accept.',
    latest: { cid, version, timestamp, signatures: [{ signer: k1.pubHex, signature: sig1 }] },
    trustedSigners: [k1.pubHex],
    threshold: 1,
    expectedValid: true,
    expectedValidCount: 1,
  },
  {
    name: 'valid_legacy_single',
    description: 'Legacy single-sig format (signer/signature fields, no signatures[]) → accept.',
    latest: { cid, version, timestamp, signer: k1.pubHex, signature: sig1 },
    trustedSigners: [k1.pubHex],
    threshold: 1,
    expectedValid: true,
    expectedValidCount: 1,
  },
  {
    name: 'tampered_sig',
    description: 'Signature bytes altered → fails Ed25519 verify, count 0 → reject.',
    latest: { cid, version, timestamp, signatures: [{ signer: k1.pubHex, signature: tamper(sig1) }] },
    trustedSigners: [k1.pubHex],
    threshold: 1,
    expectedValid: false,
    expectedValidCount: 0,
  },
  {
    name: 'untrusted_signer',
    description: 'Cryptographically valid signature, but signer is not in the trusted set → not counted.',
    latest: { cid, version, timestamp, signatures: [{ signer: k2.pubHex, signature: sig2 }] },
    trustedSigners: [k1.pubHex],
    threshold: 1,
    expectedValid: false,
    expectedValidCount: 0,
  },
  {
    name: 'threshold_not_met',
    description: 'One valid signature but threshold is 2 → reject (validCount 1 < 2).',
    latest: { cid, version, timestamp, signatures: [{ signer: k1.pubHex, signature: sig1 }] },
    trustedSigners: [k1.pubHex, k2.pubHex],
    threshold: 2,
    expectedValid: false,
    expectedValidCount: 1,
  },
];

const out = {
  _comment: 'GENERATED by scripts/gen-test-vectors.mjs — do not hand-edit. Test fixtures only; keys are public, no secrets.',
  vectors,
};

mkdirSync(join(ROOT, 'testdata'), { recursive: true });
writeFileSync(join(ROOT, 'testdata', 'latest.vectors.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote testdata/latest.vectors.json with ${vectors.length} vectors`);
console.log(`  test signer 1 (trusted):   ${k1.pubHex}`);
console.log(`  test signer 2 (untrusted): ${k2.pubHex}`);
